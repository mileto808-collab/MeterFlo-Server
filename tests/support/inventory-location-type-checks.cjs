const assert = require("node:assert/strict");
const fs = require("node:fs");

module.exports = async function ({ page, api, command, root, fixture, expect }) {
  const state = (await api("GET", `${root}/inventory`)).state;
  const warehouse = state.warehouses.find(location => location.id === "wizard-w");
  const physicalType = state.locationTypes.find(type => type.id === warehouse.locationTypeId);
  const customType = { id: crypto.randomUUID(), name: "Custom depot type", kind: physicalType.kind, accessPolicy: physicalType.accessPolicy };
  await command("locationType", customType);
  await command("warehouse", { ...warehouse, locationTypeId: customType.id });
  const expected = await api("GET", `${root}/inventory/stock?locationType=${customType.id}&limit=100`);
  assert.ok(expected.filtered > 0);
  assert.equal(expected.rows.length, expected.filtered);
  assert.ok(expected.rows.every(row => row.warehouse.locationTypeId === customType.id && row.warehouseId === warehouse.id));
  page.once("dialog", dialog => dialog.accept());
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`/projects/${fixture.projectId}/inventory`);
  await page.getByRole("tab", { name: "Stock & search", exact: true }).click();
  await page.getByRole("button", { name: "Filters", exact: true }).click();
  const dialog = page.getByRole("dialog");
  await dialog.getByLabel("Location type", { exact: true }).selectOption(customType.id);
  await dialog.getByRole("button", { name: new RegExp(`^Show ${expected.filtered} balances?$`) }).click();
  const downloadEvent = page.waitForEvent("download");
  await page.getByRole("button", { name: "CSV", exact: true }).click();
  const download = await downloadEvent, csv = fs.readFileSync(await download.path(), "utf8");
  assert.ok(csv.includes(customType.name));
  assert.ok(!csv.includes("Shared service van"), "Location-type export must not broaden to other locations");
  const renamed = { ...customType, name: "Renamed depot type", expectedRevision: 1 };
  await command("locationType", renamed);
  const afterRename = await api("GET", `${root}/inventory/stock?locationType=${customType.id}&limit=100`);
  assert.equal(afterRename.filtered, expected.filtered);
  assert.ok(afterRename.rows.every(row => row.warehouse.locationTypeName === renamed.name));
  await page.reload();
  await page.getByRole("button", { name: "Filters", exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await dialog.getByLabel("Location type", { exact: true }).selectOption(customType.id);
  await expect(dialog.getByLabel("Location type", { exact: true })).toHaveValue(customType.id);
  await page.screenshot({ path: "generated-artifacts/wizard-use/stock-location-type-phone.jpg", fullPage: true });
  await dialog.getByRole("button", { name: "Clear filters", exact: true }).click();
  await expect(dialog.getByLabel("Location type", { exact: true })).toHaveValue("all");
  await dialog.getByRole("button", { name: /^Show .*balances?$/ }).click();
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.goto(`/projects/${fixture.projectId}/edit`);
  await page.getByRole("tab", { name: "Inventory", exact: true }).click();
  const settings = page.getByRole("region", { name: "Field inventory settings" });
  await expect(settings).toBeVisible();
  await page.screenshot({ path: "generated-artifacts/wizard-use/project-inventory-settings-desktop.jpg", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await settings.getByRole("button", { name: "Save field inventory settings" }).scrollIntoViewIfNeeded();
  await expect(settings).toBeVisible();
  await page.screenshot({ path: "generated-artifacts/wizard-use/project-inventory-settings-phone.jpg", fullPage: true });
  console.log("PASS: relational custom location-type filtering, stable rename IDs, filtered CSV, phone filters, and project Inventory tab.");
};
