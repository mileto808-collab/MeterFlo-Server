const { chromium, expect } = require("@playwright/test");
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");

(async () => {
  if (!process.env.WORKSPACE_UI_SANDBOX_CONFIG) throw new Error("Owned sandbox required.");
  const fixture = JSON.parse(await fs.readFile("/tmp/meterflo-inventory-ui-fixture.json", "utf8"));
  const browser = await chromium.launch({ executablePath: "/repl/tools/bin/chromium", args: ["--no-sandbox"] });
  const context = await browser.newContext({ baseURL: require("./support/workspace-ui-base.cjs")() });
  try {
    const login = await context.request.post("/api/auth/local/login", { data: fixture });
    assert.ok(login.ok());
    const page = await context.newPage(), errors = [];
    page.on("pageerror", e => errors.push(e.message));
    const workOrders = `/projects/${fixture.projectId}/work-orders`;
    const inventory = `/projects/${fixture.projectId}/inventory`;
    await page.goto(workOrders);
    await expect(page.getByTestId("inventory-crew-help")).toBeVisible();
    await page.getByTestId(`nav-project-${fixture.projectId}-inventory`).click();
    await expect(page).toHaveURL(new RegExp(`${inventory}$`));
    await expect(page.getByRole("tab", { name: "Stock & search" })).toHaveAttribute("data-state", "active");
    await page.getByRole("tab", { name: "Locations" }).click();
    await expect(page.getByRole("tab", { name: "Locations" })).toHaveAttribute("data-state", "active");
    await page.goBack();
    await expect(page).toHaveURL(new RegExp(`${inventory}$`));
    await expect(page.getByRole("tab", { name: "Stock & search" })).toHaveAttribute("data-state", "active");
    await page.goForward();
    await expect(page.getByRole("tab", { name: "Locations" })).toHaveAttribute("data-state", "active");
    const addLocation = page.getByRole("button", { name: "Add location" });
    await addLocation.click();
    await expect(addLocation).toBeHidden();
    await page.goBack();
    await expect(addLocation).toBeVisible();
    await page.goBack();
    await page.getByTestId("button-start-inventory-desktop").click();
    await expect(page.getByTestId("inventory-task-fulfillment")).toBeVisible();
    await page.getByTestId("inventory-task-fulfillment").click();
    await expect(page.getByText("Choose a fulfillment workflow")).toBeVisible();
    await page.goBack();
    await expect(page.getByTestId("inventory-task-fulfillment")).toBeVisible();
    await page.goBack();
    await expect(page.getByRole("tab", { name: "Stock & search" })).toHaveAttribute("data-state", "active");
    await page.goBack();
    await expect(page).toHaveURL(new RegExp(`${workOrders}$`));
    await page.setViewportSize({ width: 390, height: 844 });
    await expect(page.getByTestId("inventory-crew-help")).toBeHidden();
    await page.getByTestId("button-sidebar-toggle").click();
    await page.getByTestId(`nav-project-${fixture.projectId}-inventory`).click();
    await expect(page).toHaveURL(new RegExp(`${inventory}$`));
    await expect(page.getByTestId("nav-projects")).toBeHidden();
    await page.getByTestId("button-start-inventory-mobile").click();
    await expect(page.getByTestId("inventory-task-fulfillment")).toBeVisible();
    await page.goBack();
    await expect(page.getByTestId("button-start-inventory-mobile")).toBeVisible();
    await page.getByTestId("button-sidebar-toggle").click();
    await page.getByTestId(`nav-project-${fixture.projectId}-work-orders`).click();
    await expect(page).toHaveURL(new RegExp(`${workOrders}$`));
    await expect(page.getByTestId("nav-projects")).toBeHidden();
    assert.deepEqual(errors, [], "device back and menu transitions must not throw browser errors");
    console.log("Inventory tabs, wizard task and browser back history, responsive menu close, and mobile crew tip visibility passed.");
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
