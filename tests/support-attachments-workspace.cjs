const { chromium, request } = require("playwright");
const fs = require("node:fs/promises");
const assert = require("node:assert/strict");
(async () => {
  const config = JSON.parse(await fs.readFile(process.env.WORKSPACE_UI_SANDBOX_CONFIG, "utf8"));
  assert.equal(config.ownedWorkspaceSandbox, true);
  const fixture = JSON.parse(await fs.readFile("/tmp/meterflo-inventory-ui-fixture.json", "utf8"));
  const api = await request.newContext({ baseURL: config.baseURL });
  assert.equal((await api.post("/api/auth/local/login", { data: fixture })).status(), 200);
  const browser = await chromium.launch({ executablePath: "/repl/tools/bin/chromium", headless: true, args: ["--no-sandbox"] });
  try {
    const context = await browser.newContext({ baseURL: config.baseURL, viewport: { width: 1280, height: 850 }, storageState: await api.storageState() });
    const page = await context.newPage(), errors = [];
    page.on("pageerror", error => errors.push(error.message));
    await page.goto(`/projects/${fixture.projectId}/inventory`);
    await page.getByRole("button", { name: "Support", exact: true }).click();
    const dialog = page.getByTestId("dialog-support-form");
    await dialog.waitFor();
    await page.getByTestId("input-support-email").fill("reply@example.test");
    await page.getByTestId("input-support-subject").fill("Support attachments test");
    await page.getByTestId("textarea-support-message").fill("Please investigate the attached test diagnostic.");
    const picker = page.getByTestId("input-support-attachments");
    await picker.setInputFiles({ name: "diagnostic.log", mimeType: "text/plain", buffer: Buffer.from("test diagnostic\n") });
    await picker.setInputFiles({ name: "blocked.exe", mimeType: "application/octet-stream", buffer: Buffer.from("not allowed") });
    assert.ok((await page.getByTestId("text-support-attachment-error").textContent()).includes("not added"));
    await picker.setInputFiles({ name: "data.csv", mimeType: "text/csv", buffer: Buffer.from("id,value\n1,2\n") });
    await page.getByTestId("button-remove-support-attachment-1").click();
    assert.equal(await page.getByText("data.csv", { exact: true }).count(), 0);
    await page.screenshot({ path: "generated-artifacts/project-workspace/support-desktop.jpg" });
    const submit = page.getByTestId("button-support-submit");
    const responsePromise = page.waitForResponse(response => response.url().endsWith("/api/support") && response.request().method() === "POST");
    await submit.click();
    const response = await responsePromise;
    assert.equal(response.status(), 502, await response.text());
    assert.equal((await response.json()).emailSent, false);
    assert.equal(await page.getByTestId("textarea-support-message").inputValue(), "Please investigate the attached test diagnostic.");
    await page.getByText("diagnostic.log", { exact: true }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.getByTestId("textarea-support-message").inputValue(), "Please investigate the attached test diagnostic.");
    await page.getByText("diagnostic.log", { exact: true }).waitFor();
    await page.screenshot({ path: "generated-artifacts/project-workspace/support-phone.jpg" });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
    await page.setViewportSize({ width: 844, height: 390 });
    assert.equal(await page.getByTestId("textarea-support-message").inputValue(), "Please investigate the attached test diagnostic.");
    await page.getByText("diagnostic.log", { exact: true }).waitFor();
    await submit.scrollIntoViewIfNeeded();
    await page.screenshot({ path: "generated-artifacts/project-workspace/support-landscape.jpg" });
    assert.ok(await submit.isVisible());
    await page.route("**/api/support", async route => {
      const body = route.request().postDataBuffer().toString();
      assert.ok(body.includes('name="attachments"'));
      assert.ok(body.includes('filename="diagnostic.log"'));
      assert.ok(body.includes('name="projectId"'));
      assert.ok(body.includes(String(fixture.projectId)));
      await route.fulfill({ status: 200, contentType: "application/json", body: JSON.stringify({ emailSent: true }) });
    });
    await submit.click();
    await page.getByTestId("button-support-close").waitFor();
    await page.getByTestId("button-support-close").click();
    await page.setViewportSize({ width: 1280, height: 850 });
    await page.getByRole("button", { name: "Support", exact: true }).click();
    assert.equal(await page.getByText("diagnostic.log", { exact: true }).count(), 0);
    await page.getByTestId("button-support-cancel").click();
    assert.deepEqual(errors, []);
    console.log("Support attachments UI: add/reject/remove, real authenticated failure retaining files, multipart context, success/reset, desktop/phone/landscape passed.");
  } finally { await browser.close(); await api.dispose(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
